#Questao 8 - verificando tipos de dados com casting

#Pegando os dados e aplicando o casting em cada um
nome = str(input("Digite o seu nome: "))
idade = int(input("Digite a sua idade: "))
altura = float(input("Digite a sua altura em metros (ex: 1.75): "))

#Exibindo os tipos com a funcao type pra comprovar
print("Tipo da variável nome:", type(nome))
print("Tipo da variável idade:", type(idade))
print("Tipo da variável altura:", type(altura))